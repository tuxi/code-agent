func TestUIPreviewAdaptationValidatesLineageAndPersistsMetadata(t *testing.T) {
	root := t.TempDir()
	writeFallbackPNG(t, filepath.Join(root, "assets", "fallback.png"))
	sourceSHA := writeSourcePNG(t, root)
	layout := createLayoutRevision(t, root, sourceSHA)
	lineage := validLineage(t, layout)

	toolResult := executeUIPreview(t, root, uiPreviewArgs(t, "p1f-adaptation", "", &lineage))
	if toolResult.Failure != nil {
		t.Fatalf("adaptation failure = %+v", toolResult.Failure)
	}
	validatePreviewResult(t, toolResult.Output)
	var decoded result
	if err := json.Unmarshal(toolResult.Output, &decoded); err != nil {
		t.Fatal(err)
	}
	if decoded.Mode != "adaptation" || decoded.Lineage == nil {
		t.Fatalf("adaptation result = %+v", decoded)
	}
	if decoded.Lineage.Target != "duo_folded" || decoded.Lineage.State != "default" {
		t.Fatalf("adaptation target/state = %+v", decoded.Lineage)
	}
	if len(toolResult.Previews) != 1 || toolResult.Previews[0].Mode != preview.ModeAdaptation || toolResult.Previews[0].Lineage == nil {
		t.Fatalf("adaptation draft = %+v", toolResult.Previews)
	}

	store, err := preview.NewFSStore(t.TempDir())
	if err != nil {
		t.Fatal(err)
	}
	service := preview.NewService(store)
	produced := service.Produce(context.Background(), preview.ProduceRequest{
		SessionID: "session_p1f", TurnID: "turn_1", CallID: "call_1",
		WorkspaceRoot: root, ProducerID: "ui_preview", Capability: "ui-adaptation",
		Assets: toolResult.Assets, Drafts: toolResult.Previews,
	})
	if produced.Fatal != nil || len(produced.Rejected) != 0 || len(produced.Artifacts) != 1 {
		t.Fatalf("produce result = %+v", produced)
	}
	artifact := produced.Artifacts[0]
	if artifact.Metadata[preview.MetadataPreviewMode] != "adaptation" || artifact.Metadata[preview.MetadataLineage] == nil {
		t.Fatalf("artifact metadata = %+v", artifact.Metadata)
	}
	replay := preview.ApplyReplay([]preview.Event{{
		Kind: "preview_artifact", SessionID: artifact.SessionID, TurnID: artifact.TurnID, Artifact: &artifact,
	}})
	if replay.Error != nil || len(replay.Artifacts) != 1 {
		t.Fatalf("replay = %+v", replay)
	}
	if replay.Artifacts[0].Metadata[preview.MetadataPreviewMode] != "adaptation" {
		t.Fatalf("replay lost lineage metadata: %+v", replay.Artifacts[0].Metadata)
	}
}

