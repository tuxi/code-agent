func writeFallbackPNG(t *testing.T, path string) {
	t.Helper()
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		t.Fatal(err)
	}
	img := image.NewRGBA(image.Rect(0, 0, 40, 30))
	for y := 0; y < 30; y++ {
		for x := 0; x < 40; x++ {
			img.Set(x, y, color.RGBA{R: uint8(x * 4), G: uint8(y * 6), B: 80, A: 255})
		}
	}
	f, err := os.Create(path)
	if err != nil {
		t.Fatal(err)
	}
	if err := png.Encode(f, img); err != nil {
		_ = f.Close()
		t.Fatal(err)
	}
	if err := f.Close(); err != nil {
		t.Fatal(err)
	}
}

func TestUIPreviewProducesTypedDraftAndSanitizedAsset(t *testing.T) {
	root := t.TempDir()
	writeFallbackPNG(t, filepath.Join(root, "assets", "fallback.png"))
	tool := NewTool()
	input, _ := json.Marshal(map[string]any{
		"artifact_key":  "ui-adaptation:r4a",
		"title":         "R4a Preview",
		"summary":       "Generated by a real tool",
		"viewer_html":   `<button id="pose">Outer screen</button><script>document.getElementById("pose").onclick=()=>{}</script>`,
		"fallback_path": "assets/fallback.png",
		"fallback_text": "Static evidence",
	})
	result, err := tool.Execute(context.Background(), tools.ExecutionContext{
		WorkspaceRoot: root, SessionID: "session_r4a", TurnID: "turn_1", CallID: "call_1",
	}, input)
	if err != nil {
		t.Fatal(err)
	}
	if result.Failure != nil {
		t.Fatalf("tool failure = %+v", result.Failure)
	}
	if len(result.Assets) != 1 || result.Assets[0].AbsolutePath != "" || result.Assets[0].WorkspaceRelativePath != "assets/fallback.png" {
		t.Fatalf("fallback asset = %+v", result.Assets)
	}
	if len(result.Previews) != 1 {
		t.Fatalf("previews = %+v", result.Previews)
	}
	draft := result.Previews[0]
	if draft.ArtifactKey != "ui-adaptation:r4a" || draft.Kind != "interactive_html" || len(draft.Assets) != 1 || draft.Fallback == nil {
		t.Fatalf("draft = %+v", draft)
	}
	if draft.Assets[0].AssetID != result.Assets[0].ID || draft.Assets[0].Width != 40 || draft.Assets[0].Height != 30 {
		t.Fatalf("draft asset = %+v ref=%+v", draft.Assets[0], result.Assets[0])
	}
	binding := tool.ToolBinding()
	if binding.Capability != Capability || binding.ModelVisibility != tools.VisibilityDirect || binding.Executor != tools.ExecutorServer {
		t.Fatalf("tool binding = %+v", binding)
	}
	registry := tools.NewRegistry()
	if err := registry.Register(tool); err != nil {
		t.Fatal(err)
	}
	registered, ok := registry.Binding(tool.Name())
	if !ok || registered.Capability != Capability || registered.ModelVisibility != tools.VisibilityDirect || registered.Executor != tools.ExecutorServer {
		t.Fatalf("registered binding = %+v/%v", registered, ok)
	}
}

func TestUIPreviewRejectsFallbackOutsideWorkspace(t *testing.T) {
	root := t.TempDir()
	outside := filepath.Join(t.TempDir(), "fallback.png")
	writeFallbackPNG(t, outside)
	input, _ := json.Marshal(map[string]any{
		"artifact_key": "outside", "title": "Outside", "viewer_html": "<div></div>", "fallback_path": outside,
	})
	result, err := NewTool().Execute(context.Background(), tools.ExecutionContext{WorkspaceRoot: root}, input)
	if err != nil {
		t.Fatal(err)
	}
	if result.Failure == nil || result.Failure.Kind != "blocked" {
		t.Fatalf("outside fallback result = %+v", result)
	}
}
