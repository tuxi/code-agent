	if err := json.Unmarshal(result.Output, &out); err != nil {
		t.Fatal(err)
	}
	if out.LayoutArtifactID != "layout_p1f_test" || out.LayoutRevision < 1 {
		t.Fatalf("layout result = %+v", out)
	}
