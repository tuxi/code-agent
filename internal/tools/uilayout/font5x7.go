const maxLabelRunes = 48

func drawLabel(dst *image.RGBA, x, y int, text string, background color.RGBA, scale int) {
	if scale < 1 {
		scale = 1
	}
	runes := []rune(strings.ToUpper(text))
	if len(runes) == 0 {
		return
	}
	if len(runes) > maxLabelRunes {
		runes = append(runes[:maxLabelRunes-1], '?')
	}
	glyphWidth := 5 * scale
	glyphHeight := 7 * scale
	spacing := scale
	padding := 2 * scale
	width := len(runes)*glyphWidth + (len(runes)-1)*spacing + 2*padding
	height := glyphHeight + 2*padding

	bounds := dst.Bounds()
	x = clamp(x, bounds.Min.X, bounds.Max.X-width)
	y = clamp(y, bounds.Min.Y, bounds.Max.Y-height)
	if width > bounds.Dx() || height > bounds.Dy() {
		return
	}
	fillRect(dst, image.Rect(x, y, x+width, y+height), background)

	textColor := color.RGBA{255, 255, 255, 255}
	cursor := x + padding
	for _, r := range runes {
		glyph, ok := glyph5x7[r]
		if !ok {
			glyph = glyph5x7['?']
		}
		for row := 0; row < 7; row++ {
			for column := 0; column < 5; column++ {
				if glyph[row]&(1<<uint(4-column)) == 0 {
					continue
				}
				px := cursor + column*scale
				py := y + padding + row*scale
				fillRect(dst, image.Rect(px, py, px+scale, py+scale), textColor)
			}
		}
		cursor += glyphWidth + spacing
	}
}

func fillRect(dst *image.RGBA, rect image.Rectangle, c color.RGBA) {
	rect = rect.Intersect(dst.Bounds())
	if rect.Empty() {
		return
	}
	for y := rect.Min.Y; y < rect.Max.Y; y++ {
		for x := rect.Min.X; x < rect.Max.X; x++ {
			dst.SetRGBA(x, y, c)
		}
	}
}

func strokeRect(dst *image.RGBA, rect image.Rectangle, thickness int, c color.RGBA) {
	if thickness < 1 {
		thickness = 1
	}
	rect = rect.Intersect(dst.Bounds())
	if rect.Empty() {
		return
	}
	fillRect(dst, image.Rect(rect.Min.X, rect.Min.Y, rect.Max.X, rect.Min.Y+thickness), c)
	fillRect(dst, image.Rect(rect.Min.X, rect.Max.Y-thickness, rect.Max.X, rect.Max.Y), c)
	fillRect(dst, image.Rect(rect.Min.X, rect.Min.Y, rect.Min.X+thickness, rect.Max.Y), c)
	fillRect(dst, image.Rect(rect.Max.X-thickness, rect.Min.Y, rect.Max.X, rect.Max.Y), c)
}

func clamp(value, low, high int) int {
	if high < low {
		return low
	}
	if value < low {
		return low
	}
	if value > high {
		return high
	}
	return value
}
